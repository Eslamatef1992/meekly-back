const { DataTypes } = require('sequelize');
module.exports = sequelize => sequelize.define('Employee', {
  id:                  { type: DataTypes.BIGINT.UNSIGNED, primaryKey: true, autoIncrement: true },
  branch_id:           { type: DataTypes.INTEGER.UNSIGNED, allowNull: false },
  employee_no:         { type: DataTypes.STRING(30), allowNull: false, unique: true },
  full_name:           { type: DataTypes.STRING(160), allowNull: false },
  full_name_ar:        { type: DataTypes.STRING(160) },
  email:               { type: DataTypes.STRING(160) },
  phone:               { type: DataTypes.STRING(40) },
  image_url:           { type: DataTypes.STRING(500), allowNull: true },
  gender:              { type: DataTypes.ENUM('male','female') },
  date_of_birth:       { type: DataTypes.DATEONLY },
  nationality:         { type: DataTypes.STRING(80) },
  civil_id_no:         { type: DataTypes.STRING(40) },
  civil_id_expiry:     { type: DataTypes.DATEONLY },
  passport_no:         { type: DataTypes.STRING(40) },
  passport_expiry:     { type: DataTypes.DATEONLY },
  work_permit_no:      { type: DataTypes.STRING(40) },
  work_permit_expiry:  { type: DataTypes.DATEONLY },
  driving_license_no:        { type: DataTypes.STRING(40), allowNull: true },
  driving_license_expiry:    { type: DataTypes.DATEONLY,   allowNull: true },
  car_plate_no:              { type: DataTypes.STRING(30), allowNull: true },
  car_registration_expiry:   { type: DataTypes.DATEONLY,   allowNull: true },
  health_card_expiry:        { type: DataTypes.DATEONLY,   allowNull: true },
  residency_expiry:    { type: DataTypes.DATEONLY },
  last_leave_return_date: { type: DataTypes.DATEONLY },
  notes:               { type: DataTypes.TEXT, allowNull: true },  // تاريخ آخر رجوع من إجازة — last return from annual leave
  department_id:       { type: DataTypes.INTEGER.UNSIGNED },
  job_title:           { type: DataTypes.STRING(120) },
  job_title_ar:        { type: DataTypes.STRING(120) },
  hire_date:           { type: DataTypes.DATEONLY, allowNull: false },
  probation_end:       { type: DataTypes.DATEONLY },
  end_date:            { type: DataTypes.DATEONLY },
  contract_type:       { type: DataTypes.ENUM('limited','unlimited'), defaultValue: 'unlimited' },
  basic_salary:        { type: DataTypes.DECIMAL(18,3), defaultValue: 0 },
  manual_salary:       { type: DataTypes.DECIMAL(18,3), defaultValue: 0 },  // الراتب اليدوي — cash-in-hand portion paid outside bank
  work_permit_salary:  { type: DataTypes.DECIMAL(18,3), defaultValue: 0 },  // الرتب حسب اذن العمل — salary declared on Iqama
  housing_allowance:   { type: DataTypes.DECIMAL(18,3), defaultValue: 0 },
  transport_allowance: { type: DataTypes.DECIMAL(18,3), defaultValue: 0 },
  other_allowance:     { type: DataTypes.DECIMAL(18,3), defaultValue: 0 },
  bank_name:           { type: DataTypes.STRING(120) },
  bank_iban:           { type: DataTypes.STRING(40) },
  status:              { type: DataTypes.ENUM('active','on_leave','terminated','resigned'), defaultValue: 'active' },
  created_at:          { type: DataTypes.DATE },
  updated_at:          { type: DataTypes.DATE },
}, { tableName: 'employees' });

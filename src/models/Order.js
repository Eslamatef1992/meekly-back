const { DataTypes } = require('sequelize');
module.exports = sequelize => sequelize.define('Order', {
  id:               { type: DataTypes.BIGINT.UNSIGNED, primaryKey: true, autoIncrement: true },
  order_no:         { type: DataTypes.STRING(30), unique: true, allowNull: false },
  branch_id:        { type: DataTypes.INTEGER.UNSIGNED, allowNull: false },
  customer_id:      { type: DataTypes.BIGINT.UNSIGNED, allowNull: true },
  customer_email:   { type: DataTypes.STRING(160), allowNull: false },
  customer_name:    { type: DataTypes.STRING(160), allowNull: false },
  customer_phone:   { type: DataTypes.STRING(40) },
  shipping_address: { type: DataTypes.STRING(500), allowNull: false },
  shipping_city:    { type: DataTypes.STRING(80) },
  shipping_area:    { type: DataTypes.STRING(80) },
  subtotal:         { type: DataTypes.DECIMAL(18,3), defaultValue: 0 },
  shipping_fee:     { type: DataTypes.DECIMAL(18,3), defaultValue: 0 },
  tax:              { type: DataTypes.DECIMAL(18,3), defaultValue: 0 },
  discount:         { type: DataTypes.DECIMAL(18,3), defaultValue: 0 },
  total:            { type: DataTypes.DECIMAL(18,3), defaultValue: 0 },
  currency_code:    { type: DataTypes.CHAR(3), defaultValue: 'KWD' },
  status:           { type: DataTypes.ENUM('pending','confirmed','processing','shipped','delivered','cancelled','refunded'), defaultValue: 'pending' },
  payment_status:   { type: DataTypes.ENUM('unpaid','paid','refunded','partial'), defaultValue: 'unpaid' },
  payment_method:   { type: DataTypes.STRING(40) },
  notes:            { type: DataTypes.STRING(500) },
  placed_at:        { type: DataTypes.DATE },
}, { tableName: 'orders' });
